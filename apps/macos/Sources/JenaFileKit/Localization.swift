/// The UI text for `korean` in the current language. `%@` are replaced by `args` in order.
public func L(_ korean: String, _ args: String...) -> String {
    let template = Localization.useEnglish ? (Localization.english[korean] ?? korean) : korean
    var out = ""
    var rest = Substring(template)
    var values = args.makeIterator()
    while let r = rest.range(of: "%@") {
        out += rest[..<r.lowerBound]
        out += values.next() ?? ""
        rest = rest[r.upperBound...]
    }
    return out + rest
}
